CREATE OR ALTER PROCEDURE PA_LISTA_OFERTA
AS
BEGIN
    SET NOCOUNT ON;

    SELECT O.ID_OFERTA, O.CODIGO, O.NOMBRE_OFERTA, P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, O.DESCRIPCION,
           O.FECHA_INICIO, O.FECHA_FIN, O.DESCUENTO, O.ESTADO, O.FECHA_CREACION,
           O.ID_USUARIO_CREACION, O.ID_USUARIO_MODIFICACION, O.FECHA_MODIFICACION
    FROM OFERTA O
    INNER JOIN PRODUCTO P ON O.ID_PRODUCTO = P.ID_PRODUCTO
    WHERE O.ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_OFERTA_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*)
    FROM OFERTA O
    INNER JOIN PRODUCTO P ON O.ID_PRODUCTO = P.ID_PRODUCTO
    WHERE O.ELIMINADO = 0;

    SELECT O.ID_OFERTA, O.CODIGO, O.NOMBRE_OFERTA, P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, O.DESCRIPCION,
           O.FECHA_INICIO, O.FECHA_FIN, O.DESCUENTO, O.ESTADO, O.FECHA_CREACION,
           O.ID_USUARIO_CREACION, O.ID_USUARIO_MODIFICACION, O.FECHA_MODIFICACION
    FROM OFERTA O
    INNER JOIN PRODUCTO P ON O.ID_PRODUCTO = P.ID_PRODUCTO
    WHERE O.ELIMINADO = 0
    ORDER BY O.ID_OFERTA
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_OFERTA(
    @Id_Oferta INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT O.ID_OFERTA, O.CODIGO, O.NOMBRE_OFERTA, P.ID_PRODUCTO, P.CODIGO AS CODIGO_PRODUCTO, P.DESCRIPCION AS DESCRIPCION_PRODUCTO,
           C.ID_CATEGORIA, C.CODIGO AS CODIGO_CATEGORIA, C.NOMBRE_CATEGORIA, C.ESTADO AS ESTADO_CATEGORIA,
           P.PAIS_ORIGEN, P.ESTADO AS ESTADO_PRODUCTO, P.NOMBRE_PRODUCTO, O.DESCRIPCION,
           O.FECHA_INICIO, O.FECHA_FIN, O.DESCUENTO, O.ESTADO,
           O.ID_USUARIO_CREACION, O.FECHA_CREACION, O.ID_USUARIO_MODIFICACION, O.FECHA_MODIFICACION, O.ELIMINADO
    FROM OFERTA O
    INNER JOIN PRODUCTO P ON O.ID_PRODUCTO = P.ID_PRODUCTO
    INNER JOIN CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
    WHERE O.ID_OFERTA = @Id_Oferta AND O.ELIMINADO = 0;
END;
GO

-- Nota: en el script original @Descuento era INT (truncaba los decimales); la columna es DECIMAL(5,2).
CREATE OR ALTER PROCEDURE PA_REGISTRAR_OFERTA(
    @Codigo VARCHAR(10),
    @Nombre_Oferta VARCHAR(50),
    @Id_Producto INT,
    @Descripcion VARCHAR(250),
    @Fecha_Inicio DATE,
    @Fecha_Fin DATE,
    @Descuento DECIMAL(5,2),
    @Estado BIT,
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO OFERTA (CODIGO, NOMBRE_OFERTA, ID_PRODUCTO, DESCRIPCION, FECHA_INICIO, FECHA_FIN, DESCUENTO, ESTADO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Nombre_Oferta, @Id_Producto, @Descripcion, @Fecha_Inicio, @Fecha_Fin, @Descuento, @Estado, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_OFERTA(
    @Id_Oferta INT,
    @Nombre_Oferta VARCHAR(50),
    @Id_Producto INT,
    @Descripcion VARCHAR(250),
    @Fecha_Inicio DATE,
    @Fecha_Fin DATE,
    @Descuento DECIMAL(5,2),
    @Estado BIT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE OFERTA
    SET NOMBRE_OFERTA = @Nombre_Oferta, ID_PRODUCTO = @Id_Producto, DESCRIPCION = @Descripcion,
        FECHA_INICIO = @Fecha_Inicio, FECHA_FIN = @Fecha_Fin, DESCUENTO = @Descuento, ESTADO = @Estado,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_OFERTA = @Id_Oferta AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_ELIMINAR_OFERTA(
    @Id_Oferta INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE OFERTA
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_OFERTA = @Id_Oferta AND ELIMINADO = 0;
END;
GO
