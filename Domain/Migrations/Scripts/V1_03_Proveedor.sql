CREATE OR ALTER PROCEDURE PA_LISTA_PROVEEDOR
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_PROVEEDOR, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM PROVEEDOR
    WHERE ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_PROVEEDOR_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*) FROM PROVEEDOR WHERE ELIMINADO = 0;

    SELECT ID_PROVEEDOR, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM PROVEEDOR
    WHERE ELIMINADO = 0
    ORDER BY ID_PROVEEDOR
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_PROVEEDOR(
    @Id_Proveedor INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_PROVEEDOR, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM PROVEEDOR
    WHERE ID_PROVEEDOR = @Id_Proveedor AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_PROVEEDOR(
    @Codigo VARCHAR(10),
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Estado BIT,
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO PROVEEDOR (CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, ESTADO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Nombres, @Apellidos, @Cedula, @Telefono, @Correo_Electronico, @Estado, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_PROVEEDOR(
    @Id_Proveedor INT,
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Estado BIT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE PROVEEDOR
    SET NOMBRES = @Nombres, APELLIDOS = @Apellidos, CEDULA = @Cedula, TELEFONO = @Telefono,
        CORREO_ELECTRONICO = @Correo_Electronico, ESTADO = @Estado,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_PROVEEDOR = @Id_Proveedor AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_ELIMINAR_PROVEEDOR(
    @Id_Proveedor INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE PROVEEDOR
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_PROVEEDOR = @Id_Proveedor AND ELIMINADO = 0;
END;
GO
