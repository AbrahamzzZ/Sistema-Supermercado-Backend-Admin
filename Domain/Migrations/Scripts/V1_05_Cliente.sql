CREATE OR ALTER PROCEDURE PA_LISTA_CLIENTE
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_CLIENTE, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM CLIENTE
    WHERE ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_CLIENTE_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*) FROM CLIENTE WHERE ELIMINADO = 0;

    SELECT ID_CLIENTE, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM CLIENTE
    WHERE ELIMINADO = 0
    ORDER BY ID_CLIENTE
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_CLIENTE(
    @Id_Cliente INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_CLIENTE, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM CLIENTE
    WHERE ID_CLIENTE = @Id_Cliente AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_CLIENTE(
    @Codigo VARCHAR(10),
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO CLIENTE (CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Nombres, @Apellidos, @Cedula, @Telefono, @Correo_Electronico, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_CLIENTE(
    @Id_Cliente INT,
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE CLIENTE
    SET NOMBRES = @Nombres, APELLIDOS = @Apellidos, CEDULA = @Cedula, TELEFONO = @Telefono,
        CORREO_ELECTRONICO = @Correo_Electronico,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_CLIENTE = @Id_Cliente AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_ELIMINAR_CLIENTE(
    @Id_Cliente INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE CLIENTE
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_CLIENTE = @Id_Cliente AND ELIMINADO = 0;
END;
GO
