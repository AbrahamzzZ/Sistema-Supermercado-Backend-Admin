CREATE OR ALTER PROCEDURE PA_LISTA_PRODUCTO
AS
BEGIN
    SET NOCOUNT ON;

    SELECT P.ID_PRODUCTO, P.CODIGO, P.DESCRIPCION, P.NOMBRE_PRODUCTO, C.ID_CATEGORIA, C.NOMBRE_CATEGORIA, P.PAIS_ORIGEN, P.ESTADO,
           P.ID_USUARIO_CREACION, P.FECHA_CREACION, P.ID_USUARIO_MODIFICACION, P.FECHA_MODIFICACION
    FROM PRODUCTO P
    INNER JOIN CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
    WHERE P.ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_PRODUCTO_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*)
    FROM PRODUCTO P
    INNER JOIN CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
    WHERE P.ELIMINADO = 0;

    SELECT P.ID_PRODUCTO, P.CODIGO, P.DESCRIPCION, P.NOMBRE_PRODUCTO, C.ID_CATEGORIA, C.NOMBRE_CATEGORIA, P.PAIS_ORIGEN, P.ESTADO,
           P.ID_USUARIO_CREACION, P.FECHA_CREACION, P.ID_USUARIO_MODIFICACION, P.FECHA_MODIFICACION
    FROM PRODUCTO P
    INNER JOIN CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
    WHERE P.ELIMINADO = 0
    ORDER BY P.ID_PRODUCTO
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_PRODUCTO(
    @Id_Producto INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT P.ID_PRODUCTO, P.CODIGO, P.DESCRIPCION, P.NOMBRE_PRODUCTO, C.ID_CATEGORIA, C.NOMBRE_CATEGORIA, P.PAIS_ORIGEN, P.ESTADO,
           P.ID_USUARIO_CREACION, P.FECHA_CREACION, P.ID_USUARIO_MODIFICACION, P.FECHA_MODIFICACION, P.ELIMINADO
    FROM PRODUCTO P
    INNER JOIN CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
    WHERE P.ID_PRODUCTO = @Id_Producto AND P.ELIMINADO = 0;
END;
GO

-- Nota: en el script original el parámetro se llamaba @Descripion (typo); se corrige a @Descripcion.
CREATE OR ALTER PROCEDURE PA_REGISTRAR_PRODUCTO(
    @Codigo VARCHAR(10),
    @Descripcion NVARCHAR(50),
    @Nombre_Producto NVARCHAR(30),
    @Id_Categoria INT,
    @Pais_Origen VARCHAR(30),
    @Estado BIT,
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO PRODUCTO (CODIGO, DESCRIPCION, NOMBRE_PRODUCTO, ID_CATEGORIA, PAIS_ORIGEN, ESTADO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Descripcion, @Nombre_Producto, @Id_Categoria, @Pais_Origen, @Estado, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_PRODUCTO(
    @Id_Producto INT,
    @Descripcion NVARCHAR(50),
    @Nombre_Producto NVARCHAR(30),
    @Id_Categoria INT,
    @Pais_Origen VARCHAR(30),
    @Estado BIT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE PRODUCTO
    SET DESCRIPCION = @Descripcion, NOMBRE_PRODUCTO = @Nombre_Producto, ID_CATEGORIA = @Id_Categoria,
        PAIS_ORIGEN = @Pais_Origen, ESTADO = @Estado,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_PRODUCTO = @Id_Producto AND ELIMINADO = 0;
END;
GO

-- No se puede eliminar un producto con ofertas activas (antes lo impedía la FK; error 50547).
CREATE OR ALTER PROCEDURE PA_ELIMINAR_PRODUCTO(
    @Id_Producto INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    IF EXISTS (SELECT 1 FROM OFERTA WHERE ID_PRODUCTO = @Id_Producto AND ELIMINADO = 0)
        THROW 50547, N'El producto tiene ofertas asociadas.', 1;

    UPDATE PRODUCTO
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_PRODUCTO = @Id_Producto AND ELIMINADO = 0;
END;
GO
