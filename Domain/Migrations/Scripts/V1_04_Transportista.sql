CREATE OR ALTER PROCEDURE PA_LISTA_TRANSPORTISTA
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_TRANSPORTISTA, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, IMAGEN, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM TRANSPORTISTA
    WHERE ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_TRANSPORTISTA_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*) FROM TRANSPORTISTA WHERE ELIMINADO = 0;

    SELECT ID_TRANSPORTISTA, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, IMAGEN, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM TRANSPORTISTA
    WHERE ELIMINADO = 0
    ORDER BY ID_TRANSPORTISTA
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_TRANSPORTISTA(
    @Id_Transportista INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_TRANSPORTISTA, CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, IMAGEN, ESTADO,
           ID_USUARIO_CREACION, FECHA_CREACION, ID_USUARIO_MODIFICACION, FECHA_MODIFICACION, ELIMINADO
    FROM TRANSPORTISTA
    WHERE ID_TRANSPORTISTA = @Id_Transportista AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_TRANSPORTISTA(
    @Codigo VARCHAR(10),
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Imagen VARBINARY(MAX) = NULL,
    @Estado BIT,
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO TRANSPORTISTA (CODIGO, NOMBRES, APELLIDOS, CEDULA, TELEFONO, CORREO_ELECTRONICO, IMAGEN, ESTADO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Nombres, @Apellidos, @Cedula, @Telefono, @Correo_Electronico, @Imagen, @Estado, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_TRANSPORTISTA(
    @Id_Transportista INT,
    @Nombres VARCHAR(30),
    @Apellidos VARCHAR(30),
    @Cedula VARCHAR(10),
    @Telefono VARCHAR(10),
    @Correo_Electronico VARCHAR(50),
    @Imagen VARBINARY(MAX) = NULL,
    @Estado BIT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE TRANSPORTISTA
    SET NOMBRES = @Nombres, APELLIDOS = @Apellidos, CEDULA = @Cedula, TELEFONO = @Telefono,
        CORREO_ELECTRONICO = @Correo_Electronico, IMAGEN = @Imagen, ESTADO = @Estado,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_TRANSPORTISTA = @Id_Transportista AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_ELIMINAR_TRANSPORTISTA(
    @Id_Transportista INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE TRANSPORTISTA
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_TRANSPORTISTA = @Id_Transportista AND ELIMINADO = 0;
END;
GO
