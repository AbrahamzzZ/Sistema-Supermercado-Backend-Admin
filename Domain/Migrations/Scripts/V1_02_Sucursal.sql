CREATE OR ALTER PROCEDURE PA_LISTA_SUCURSAL
AS
BEGIN
    SET NOCOUNT ON;

    SELECT S.ID_SUCURSAL, S.CODIGO, N.ID_NEGOCIO, S.NOMBRE_SUCURSAL, S.DIRECCION_SUCURSAL,
           S.UBICACION_SUCURSAL.Lat AS LATITUD, S.UBICACION_SUCURSAL.Long AS LONGITUD,
           S.CIUDAD_SUCURSAL, S.ESTADO,
           S.ID_USUARIO_CREACION, S.FECHA_CREACION, S.ID_USUARIO_MODIFICACION, S.FECHA_MODIFICACION
    FROM SUCURSAL S
    INNER JOIN NEGOCIO N ON S.ID_NEGOCIO = N.ID_NEGOCIO
    WHERE S.ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_LISTA_SUCURSAL_PAGINACION(
    @PageNumber INT = 1,
    @PageSize INT = 10
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TotalCount INT;
    SELECT @TotalCount = COUNT(*)
    FROM SUCURSAL S
    INNER JOIN NEGOCIO N ON S.ID_NEGOCIO = N.ID_NEGOCIO
    WHERE S.ELIMINADO = 0;

    SELECT S.ID_SUCURSAL, S.CODIGO, N.ID_NEGOCIO, S.NOMBRE_SUCURSAL, S.DIRECCION_SUCURSAL,
           S.UBICACION_SUCURSAL.Lat AS LATITUD, S.UBICACION_SUCURSAL.Long AS LONGITUD,
           S.CIUDAD_SUCURSAL, S.ESTADO,
           S.ID_USUARIO_CREACION, S.FECHA_CREACION, S.ID_USUARIO_MODIFICACION, S.FECHA_MODIFICACION
    FROM SUCURSAL S
    INNER JOIN NEGOCIO N ON S.ID_NEGOCIO = N.ID_NEGOCIO
    WHERE S.ELIMINADO = 0
    ORDER BY S.ID_SUCURSAL
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;

    SELECT @TotalCount AS TotalCount;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_SUCURSAL(
    @Id_Sucursal INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT S.ID_SUCURSAL, S.CODIGO, O.ID_NEGOCIO, O.NOMBRE AS NOMBRE_NEGOCIO, O.TELEFONO, O.RUC, O.DIRECCION,
           O.CORREO_ELECTRONICO, S.NOMBRE_SUCURSAL, S.DIRECCION_SUCURSAL,
           S.UBICACION_SUCURSAL.Lat AS LATITUD, S.UBICACION_SUCURSAL.Long AS LONGITUD,
           S.CIUDAD_SUCURSAL, S.ESTADO,
           S.ID_USUARIO_CREACION, S.FECHA_CREACION, S.ID_USUARIO_MODIFICACION, S.FECHA_MODIFICACION
    FROM SUCURSAL S
    INNER JOIN NEGOCIO O ON S.ID_NEGOCIO = O.ID_NEGOCIO
    WHERE S.ID_SUCURSAL = @Id_Sucursal AND S.ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_SUCURSAL(
    @Id_Negocio INT,
    @Codigo VARCHAR(10),
    @Nombre VARCHAR(30),
    @Direccion VARCHAR(250),
    @Ubicacion GEOGRAPHY,
    @Ciudad VARCHAR(30),
    @Estado BIT,
    @Id_Usuario_Creacion INT = NULL
)
AS
BEGIN
    INSERT INTO SUCURSAL (CODIGO, ID_NEGOCIO, NOMBRE_SUCURSAL, DIRECCION_SUCURSAL, UBICACION_SUCURSAL, CIUDAD_SUCURSAL, ESTADO, ID_USUARIO_CREACION)
    VALUES (@Codigo, @Id_Negocio, @Nombre, @Direccion, @Ubicacion, @Ciudad, @Estado, @Id_Usuario_Creacion);
END;
GO

CREATE OR ALTER PROCEDURE PA_EDITAR_SUCURSAL(
    @Id_Sucursal INT,
    @Nombre VARCHAR(30),
    @Direccion VARCHAR(250),
    @Ubicacion GEOGRAPHY,
    @Ciudad VARCHAR(30),
    @Estado BIT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE SUCURSAL
    SET NOMBRE_SUCURSAL = @Nombre, DIRECCION_SUCURSAL = @Direccion, UBICACION_SUCURSAL = @Ubicacion,
        CIUDAD_SUCURSAL = @Ciudad, ESTADO = @Estado,
        ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_SUCURSAL = @Id_Sucursal AND ELIMINADO = 0;
END;
GO

CREATE OR ALTER PROCEDURE PA_ELIMINAR_SUCURSAL(
    @Id_Sucursal INT,
    @Id_Usuario_Modificacion INT = NULL
)
AS
BEGIN
    UPDATE SUCURSAL
    SET ELIMINADO = 1, ID_USUARIO_MODIFICACION = @Id_Usuario_Modificacion, FECHA_MODIFICACION = SYSUTCDATETIME()
    WHERE ID_SUCURSAL = @Id_Sucursal AND ELIMINADO = 0;
END;
GO
